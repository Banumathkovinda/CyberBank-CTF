"""
CyberBank: Operation BlackVault
Flag Validation, Cryptographic Verification & Anti-AI Canary Service

Provides:
    - Normalization: cleans and strips whitespace / non-printable chars
    - Format validation: enforces CBANK{CATEGORY_RANDOM_IDENTIFIER} format
    - Hash generation: computes SHA-256 digests
    - Constant-time secure comparison: hmac.compare_digest
    - Anti-AI Canary Detection: identifies automated LLM prompt poison traps
"""

import re
import hmac
import hashlib

# Expected Flag Format: CBANK{CATEGORY_IDENTIFIER}
FLAG_FORMAT_REGEX = re.compile(r"^CBANK\{[A-Za-z0-9_-]+\}$")

# Anti-AI Canary Trap Signatures (Embedded in challenge sources as decoy prompt injections)
CANARY_FLAGS = {
    "CBANK{CANARY_AI_DETECTED_CHEAT_9182}",
    "CBANK{AI_BOT_DETECTED_FLAG_INVALID}",
    "CBANK{LLM_INJECTION_TRAP_DISQUALIFY_4421}",
    "CBANK{CANARY_STEGO_AI_POISON_5591}",
    "CBANK{CANARY_WEB_AI_INJECTION_7799}",
}

CANARY_SUBSTRING_PATTERNS = [
    "CANARY_AI_",
    "AI_BOT_",
    "LLM_INJECTION_",
    "AI_POISON_",
]


def normalize_flag(raw_flag: str) -> str:
    """
    Normalize candidate flag string.
    - Strips leading/trailing whitespace, newlines, and non-printable characters.
    - Preserves internal case and characters inside the brackets.
    """
    if not raw_flag:
        return ""
    cleaned = raw_flag.strip().replace("\x00", "").replace("\r", "").replace("\n", "")
    return cleaned


def validate_flag_format(flag: str) -> bool:
    """Check if the string matches the canonical CBANK{...} format."""
    if not flag:
        return False
    return bool(FLAG_FORMAT_REGEX.match(flag))


def is_canary_flag(candidate_flag: str) -> bool:
    """
    Detect if the submitted flag is an Anti-AI Prompt Canary Trap.
    Returns True if an operative submitted an injected decoy flag generated by an LLM.
    """
    normalized = normalize_flag(candidate_flag).upper()
    if not normalized:
        return False

    if normalized in {f.upper() for f in CANARY_FLAGS}:
        return True

    for pattern in CANARY_SUBSTRING_PATTERNS:
        if pattern in normalized:
            return True

    return False


def hash_flag(flag: str) -> str:
    """
    Compute cryptographic SHA-256 hash of a normalized flag.
    Never store plaintext flags in database records.
    """
    normalized = normalize_flag(flag)
    return hashlib.sha256(normalized.encode("utf-8")).hexdigest()


def verify_flag(candidate_flag: str, stored_hash: str) -> bool:
    """
    Cryptographically verify candidate flag against stored SHA-256 hash.
    Uses hmac.compare_digest for constant-time comparison to prevent timing attacks.
    """
    if not candidate_flag or not stored_hash:
        return False

    candidate_hash = hash_flag(candidate_flag)
    return hmac.compare_digest(candidate_hash.lower(), stored_hash.lower())
